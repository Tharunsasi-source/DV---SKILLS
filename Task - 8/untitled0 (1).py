import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/StudentsPerformance_preprocessed.csv")

scores = ["math score", "reading score", "writing score"]

df.groupby("parental level of education")[scores].mean().plot(
    kind="bar", figsize=(9, 5)
)
plt.title("Average Scores by Parental Education")
plt.xlabel("Education Level")
plt.ylabel("Average Score")
plt.xticks(rotation=30, ha="right")
plt.tight_layout()
plt.show()

df.groupby("lunch")[scores].mean().plot(kind="bar", figsize=(7, 5))
plt.title("Average Scores by Lunch Type")
plt.xlabel("Lunch Type")
plt.ylabel("Average Score")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

fig, axes = plt.subplots(1, 3, figsize=(14, 4))

for ax, score in zip(axes, scores):
  sns.boxplot(data=df, x="test preparation course", y=score, ax=ax)
  ax.set_title(score.title())

plt.tight_layout()
plt.show()

pairs = [
    ("math score", "reading score"),
    ("math score", "writing score"),
    ("reading score", "writing score"),
]
fig, axes = plt.subplots(1, 3, figsize=(14, 4))

for ax, (x, y) in zip(axes, pairs):
  sns.scatterplot(data=df, x=x, y=y, ax=ax)
  ax.set_title(f"{x.title()} vs {y.title()}")

plt.tight_layout()
plt.show()

plt.figure(figsize=(6, 5))
sns.heatmap(df[scores].corr(), annot=True, cmap="Blues")
plt.title("Score Correlation Heatmap")
plt.tight_layout()
plt.show()